import MancoraCore
import Testing

@testable import MancoraIO

@Suite("LUT files")
struct LUTReaderTests {
    @Test("Golden data was generated by ImageJ")
    func goldenPresent() throws {
        let golden = try #require(Fixtures.lutGolden)
        #expect(golden.imagej.hasPrefix("1."))
        #expect(golden.files.count == 37)
    }

    /// Every bundled LUT decodes to exactly what ImageJ's LutLoader produces.
    @Test("Bundled LUT matches ImageJ", arguments: Fixtures.lutFileNames.filter { $0 != "cividis.txt" })
    func matchesImageJ(file: String) throws {
        let expectedHex = try #require(Fixtures.lutGolden?.files[file] ?? nil, "ImageJ could not load \(file)")
        let expected = Fixtures.bytes(fromHex: expectedHex)
        let lut = try LUTReader.read(path: Fixtures.path("Resources/LUTs/\(file)"))
        #expect(lut.reds == Array(expected[0..<256]))
        #expect(lut.greens == Array(expected[256..<512]))
        #expect(lut.blues == Array(expected[512..<768]))
    }

    /// cividis.txt holds 0–1 floats. ImageJ truncates them (the LUT is nearly
    /// black); Mancora scales them to 0–255 on purpose.
    @Test func cividisIsScaled() throws {
        let lut = try LUTReader.read(path: Fixtures.path("Resources/LUTs/cividis.txt"))
        #expect(lut.name == "cividis")
        // First row "0.0000 0.1262 0.3015", last row "1.0000 0.9169 0.2731".
        #expect((lut.reds[0], lut.greens[0], lut.blues[0]) == (0, 32, 77))
        #expect((lut.reds[255], lut.greens[255], lut.blues[255]) == (255, 234, 70))
        let imagej = Fixtures.bytes(fromHex: try #require(Fixtures.lutGolden?.files["cividis.txt"] ?? nil))
        #expect(imagej[0..<256].allSatisfy { $0 <= 1 }, "ImageJ's truncating behavior changed; revisit the deviation")
    }

    @Test func rawLUT() throws {
        let bytes = (0..<768).map { UInt8($0 % 256) }
        let lut = try LUTReader.decode(bytes, name: "raw")
        #expect(lut.reds == lut.greens && lut.greens == lut.blues)
        #expect(lut.reds[200] == 200)
    }

    @Test func nihHeaderWithFewerColorsIsInterpolated() throws {
        // ICOL header with 128 colors, then 3×128 bytes, padded to the usual
        // 800 bytes (ImageJ only looks for a header in files over 768 bytes).
        var bytes: [UInt8] = [0x49, 0x43, 0x4F, 0x4C, 0x00, 0xA2, 0x00, 0x80, 0, 0, 0, 0x7F]
        bytes += [UInt8](repeating: 0, count: 32 - bytes.count)
        for _ in 0..<3 { bytes += (0..<128).map { UInt8($0 * 2) } }
        bytes += [UInt8](repeating: 0, count: 800 - bytes.count)
        let lut = try LUTReader.decode(bytes, name: "nih")
        // ImageJ: i1 = (int)(i*0.5), fraction 0 or 0.5 between 2·i1 and 2·(i1+1).
        #expect(lut.reds[0] == 0)
        #expect(lut.reds[1] == 1)
        #expect(lut.reds[2] == 2)
        #expect(lut.reds[255] == 254)
    }

    @Test func textLUTWithIndexColumnHeaderAndCRLF() throws {
        var text = "Index\tRed\tGreen\tBlue\r\n"
        for i in 0..<256 { text += "\(i)\t\(i)\t\(255 - i)\t\(i / 2)\r\n" }
        text += "\u{1A}"  // DOS end-of-file marker, as in phase.lut
        let lut = try LUTReader.decode(Array(text.utf8), name: "text")
        #expect(lut.reds[10] == 10)
        #expect(lut.greens[10] == 245)
        #expect(lut.blues[11] == 5)
    }

    @Test func textValuesWrapLikeJavaBytes() throws {
        var text = ""
        for i in 0..<256 { text += i == 0 ? "300, -1, 256\n" : "\(i) \(i) \(i)\n" }
        let lut = try LUTReader.decode(Array(text.utf8), name: "wrap")
        #expect((lut.reds[0], lut.greens[0], lut.blues[0]) == (44, 255, 0))
    }

    @Test func rejectsBadInput() {
        #expect(throws: MancoraIOError.self) { try LUTReader.decode([UInt8](repeating: 0, count: 500), name: "short") }
        #expect(throws: MancoraIOError.self) {
            try LUTReader.decode(Array("1 2 3\n4 5\n".utf8) + [UInt8](repeating: 0x20, count: 800), name: "ragged")
        }
        #expect(throws: MancoraIOError.self) {
            try LUTReader.decode(Array((0..<100).map { "\($0) \($0) \($0)\n" }.joined().utf8), name: "rows")
        }
        #expect(throws: MancoraIOError.self) {
            try LUTReader.read(path: Fixtures.path("Resources/LUTs/README.txt"))
        }
        // An ICOL header promising more colors than the file holds.
        var truncated: [UInt8] = [0x49, 0x43, 0x4F, 0x4C, 0x00, 0xA2, 0x01, 0x00]
        truncated += [UInt8](repeating: 1, count: 782)
        #expect(throws: MancoraIOError.self) { try LUTReader.decode(truncated, name: "trunc") }
    }

    @Test func baseName() {
        #expect(LUTReader.baseName(of: "/a/b/Cyan Hot.lut") == "Cyan Hot")
        #expect(LUTReader.baseName(of: #"C:\luts\mpl-viridis.lut"#) == "mpl-viridis")
        #expect(LUTReader.baseName(of: ".hidden") == ".hidden")
    }
}
