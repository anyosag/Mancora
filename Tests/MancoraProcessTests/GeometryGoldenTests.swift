import MancoraCore
import MancoraProcess
import Testing

/// ImageJ 1.54p's interpolation and geometric operations, written by
/// `Tools/fixtures/GeometryFixtures.java` on the inputs of `FilterInputs`.
struct GeometryGolden: Decodable {
    let imagej: String
    let inputs: [String: String]
    let cases: [Case]
    let points: [Point]

    struct Case: Decodable, Sendable, CustomTestStringConvertible {
        let op: String
        let input: String
        let params: Params
        let width: Int
        let height: Int
        let sha256: String
        let min: String?
        let max: String?
        let samples: [String: String]

        var testDescription: String { "\(op) \(input) \(params.summary)" }
    }

    struct Params: Decodable, Sendable {
        let method: String
        let roi: [Int]?
        let background: Double?
        let display: [Double]?
        let invertedLUT: Bool?
        let signed16: Bool?
        let width: Int?
        let height: Int?
        let averaging: Bool?
        let x: Double?
        let y: Double?
        let angle: Double?

        var summary: String {
            var parts = [method]
            if let width, let height { parts.append("\(width)×\(height)\(averaging == true ? " averaged" : "")") }
            if let x, let y { parts.append("x=\(x) y=\(y)") }
            if let angle { parts.append("\(angle)°") }
            if let roi { parts.append("roi \(roi.map(String.init).joined(separator: ","))") }
            if let background { parts.append("bg \(background)") }
            if let display { parts.append("display \(display[0])–\(display[1])") }
            if invertedLUT == true { parts.append("inverted LUT") }
            if signed16 == true { parts.append("signed") }
            return parts.joined(separator: " ")
        }
    }

    struct Point: Decodable, Sendable, CustomTestStringConvertible {
        let input: String
        let method: String
        let background: Double
        let x: String
        let y: String
        let interpolatedPixel: String?
        let bicubic: String?
        let pixelInterpolated: Int?
        let interpolatedValue: String
        let interpolatedRGBPixel: Int?

        var testDescription: String { "\(input) \(method) bg \(background) at (\(x), \(y))" }
    }

    static let shared: GeometryGolden? = ProcessFixtures.json(GeometryGolden.self, "Tests/Fixtures/process/geometry.json")

    static func cases(_ op: String) -> [Case] { (shared?.cases ?? []).filter { $0.op == op } }
}

@Suite("Interpolation and geometry match ImageJ")
struct GeometryGoldenTests {
    @Test("Golden data was generated by ImageJ")
    func goldenPresent() throws {
        let golden = try #require(GeometryGolden.shared)
        #expect(golden.imagej == "1.54p")
        #expect(golden.cases.count > 800)
        #expect(golden.points.count > 300)
    }

    @Test("Inputs match the fixture generator", arguments: (GeometryGolden.shared?.inputs ?? [:]).sorted { $0.key < $1.key })
    func inputs(_ input: (key: String, value: String)) throws {
        let (plane, _, _) = try #require(FilterInputs.plane(named: input.key))
        #expect(FilterInputs.sha256(plane) == input.value)
    }

    @Test("resize, with and without averaging", arguments: GeometryGolden.cases("resize"))
    func resize(_ c: GeometryGolden.Case) throws { try check(c) }

    @Test("scale", arguments: GeometryGolden.cases("scale"))
    func scale(_ c: GeometryGolden.Case) throws { try check(c) }

    @Test("rotate", arguments: GeometryGolden.cases("rotate"))
    func rotate(_ c: GeometryGolden.Case) throws { try check(c) }

    @Test("translate", arguments: GeometryGolden.cases("translate"))
    func translate(_ c: GeometryGolden.Case) throws { try check(c) }

    @Test("Interpolation at a point", arguments: GeometryGolden.shared?.points ?? [])
    func point(_ p: GeometryGolden.Point) throws {
        let (plane, width, _) = try #require(FilterInputs.plane(named: p.input))
        var ip = GeometryProcessor(plane, width: width)
        ip.interpolation = try method(p.method)
        ip.setBackgroundValue(p.background)
        let x = try #require(Double(p.x)), y = try #require(Double(p.y))
        if let expected = p.interpolatedPixel {
            #expect(same(ip.interpolatedPixel(x: x, y: y), expected), "getInterpolatedPixel")
        }
        if let expected = p.bicubic {
            #expect(same(ip.bicubicInterpolatedPixel(x: x, y: y, source: ip), expected), "getBicubicInterpolatedPixel")
        }
        if let expected = p.pixelInterpolated {
            #expect(ip.pixelInterpolated(x: x, y: y) == expected, "getPixelInterpolated")
        }
        #expect(same(ip.interpolatedValue(x: x, y: y), p.interpolatedValue), "getInterpolatedValue")
        if let expected = p.interpolatedRGBPixel {
            #expect(Int(Int32(bitPattern: ip.interpolatedRGBPixel(x: x, y: y))) == expected, "getInterpolatedRGBPixel")
        }
    }

    // MARK: Running a case

    func method(_ name: String) throws -> InterpolationMethod {
        switch name {
        case "none": return .none
        case "bilinear": return .bilinear
        case "bicubic": return .bicubic
        default: throw GoldenError.unknown(name)
        }
    }

    enum GoldenError: Error { case unknown(String) }

    /// Whether `value` is the double Java printed as `expected` (NaN equals NaN).
    func same(_ value: Double, _ expected: String) -> Bool {
        guard let e = Double(expected) else { return false }
        return value.bitPattern == e.bitPattern || (value.isNaN && e.isNaN)
    }

    /// A parameter the case must have.
    func value<T>(_ v: T?, sourceLocation: SourceLocation = #_sourceLocation) throws -> T {
        try #require(v, "parameter missing", sourceLocation: sourceLocation)
    }

    func run(_ c: GeometryGolden.Case) throws -> GeometryProcessor {
        let (plane, width, _) = try #require(FilterInputs.plane(named: c.input))
        let p = c.params
        var ip = GeometryProcessor(plane, width: width)
        // The generator's 16- and 32-bit inputs had resetMinAndMax(): their range
        // is the pixels' as they were made, even after an operation in place.
        if plane.pixelType == .gray16 || plane.pixelType == .gray32Float {
            ip.setMinAndMax(ip.displayMin, ip.displayMax)
        }
        if let display = p.display { ip.setMinAndMax(display[0], display[1]) }
        ip.invertedLUT = p.invertedLUT ?? false
        ip.signed16 = p.signed16 ?? false
        ip.interpolation = try method(p.method)
        if let roi = p.roi { ip.setRoi(RoiBounds(x: roi[0], y: roi[1], width: roi[2], height: roi[3])) }
        if let background = p.background { ip.setBackgroundValue(background) }
        switch c.op {
        case "resize":
            return ip.resized(width: try value(p.width), height: try value(p.height), averaging: try value(p.averaging))
        case "scale":
            ip.scale(x: try value(p.x), y: try value(p.y))
        case "rotate":
            ip.rotate(degrees: try value(p.angle))
        case "translate":
            ip.translate(x: try value(p.x), y: try value(p.y))
        default:
            throw GoldenError.unknown(c.op)
        }
        return ip
    }

    func check(_ c: GeometryGolden.Case) throws {
        let output = try run(c)
        #expect(output.width == c.width && output.height == c.height, "size \(output.width)×\(output.height)")
        guard output.width == c.width, output.height == c.height else { return }
        if let min = c.min, let max = c.max {
            #expect(same(output.displayMin, min) && same(output.displayMax, max),
                    "display range \(output.displayMin)–\(output.displayMax), ImageJ \(min)–\(max)")
        }
        if FilterInputs.sha256(output.plane) == c.sha256 { return }
        let mismatches = c.samples.sorted { Int($0.key)! < Int($1.key)! }.compactMap { key, expected in
            let i = Int(key)!
            return FilterInputs.sampleMatches(expected, output.plane, i)
                ? nil : "pixel \(i): ImageJ \(expected), Mancora \(FilterInputs.sample(output.plane, i))"
        }
        Issue.record("output differs from ImageJ; \(mismatches.isEmpty ? "the samples match" : mismatches.joined(separator: "; "))")
    }
}
