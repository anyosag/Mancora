import MancoraCore
import MancoraProcess
import Testing

/// ImageJ 1.54p's filter results, written by `Tools/fixtures/FilterFixtures.java`.
struct FilterGolden: Decodable {
    let imagej: String
    let inputs: [String: String]
    let cases: [Case]

    struct Case: Decodable, Sendable, CustomTestStringConvertible {
        let filter: String
        let input: String
        let params: Params
        let sha256: String
        let samples: [String: String]

        var testDescription: String { "\(filter) \(input) \(params.summary)" }
    }

    struct Params: Decodable, Sendable {
        var sigmaX, sigmaY, accuracy, radius, threshold: Double?
        var kernelWidth: Int?
        var kernel: [Double]?
        var normalize, blackBackground, padEdges: Bool?
        var iterations, count: Int?

        var summary: String {
            var parts: [String] = []
            if let sigmaX, let sigmaY { parts.append("σ=\(sigmaX),\(sigmaY)") }
            if let accuracy { parts.append("accuracy=\(accuracy)") }
            if let radius { parts.append("r=\(radius)") }
            if let threshold { parts.append("threshold=\(threshold)") }
            if let kernelWidth, let kernel { parts.append("kernel \(kernelWidth)×\(kernel.count / kernelWidth)") }
            if let normalize { parts.append(normalize ? "normalized" : "raw") }
            if let blackBackground { parts.append(blackBackground ? "black bg" : "white bg") }
            if let iterations, let count { parts.append("×\(iterations) count \(count)") }
            if padEdges == true { parts.append("padded") }
            return parts.joined(separator: " ")
        }
    }

    static let shared: FilterGolden? = ProcessFixtures.json(FilterGolden.self, "Tests/Fixtures/process/filters.json")

    static func cases(_ filters: String...) -> [Case] {
        (shared?.cases ?? []).filter { filters.contains($0.filter) }
    }
}

@Suite("Filters match ImageJ")
struct FilterGoldenTests {
    @Test("Golden data was generated by ImageJ")
    func goldenPresent() throws {
        let golden = try #require(FilterGolden.shared)
        #expect(golden.imagej == "1.54p")
        #expect(golden.cases.count > 600)
    }

    /// The Swift input generators rebuild exactly the images ImageJ filtered.
    @Test("Inputs match the fixture generator", arguments: (FilterGolden.shared?.inputs ?? [:]).sorted { $0.key < $1.key })
    func inputs(_ input: (key: String, value: String)) throws {
        let (plane, _, _) = try #require(FilterInputs.plane(named: input.key))
        #expect(FilterInputs.sha256(plane) == input.value)
    }

    @Test("Gaussian Blur", arguments: FilterGolden.cases("gaussian"))
    func gaussian(_ c: FilterGolden.Case) throws { try check(c) }

    @Test("Mean, Minimum, Maximum, Variance, Median",
          arguments: FilterGolden.cases("mean", "minimum", "maximum", "variance", "median"))
    func rank(_ c: FilterGolden.Case) throws { try check(c) }

    @Test("Remove Outliers, Remove NaNs, Despeckle",
          arguments: FilterGolden.cases("outliersBright", "outliersDark", "removeNaNs", "despeckle"))
    func noise(_ c: FilterGolden.Case) throws { try check(c) }

    @Test("Smooth, Sharpen, Find Edges", arguments: FilterGolden.cases("smooth", "sharpen", "findEdges"))
    func threeByThree(_ c: FilterGolden.Case) throws { try check(c) }

    @Test("Convolve", arguments: FilterGolden.cases("convolve"))
    func convolve(_ c: FilterGolden.Case) throws { try check(c) }

    @Test("Binary", arguments: FilterGolden.cases("erode", "dilate", "open", "close", "outline", "fill", "skeletonize"))
    func binary(_ c: FilterGolden.Case) throws { try check(c) }

    /// ImageJ's Outline with a black background reads the snapshot taken for
    /// Undo, which still holds the pixels from before Binary inverts them,
    /// so on a single image (not a stack slice) it returns something else.
    /// Mancora returns the outline, as ImageJ does for stack slices.
    @Test func outlineSnapshotQuirkIsNotReproduced() throws {
        let quirk = try #require(FilterGolden.cases("outlineSnapshotQuirk").first)
        let regular = try #require(
            FilterGolden.cases("outline").first { $0.input == quirk.input && $0.params.blackBackground == true })
        #expect(quirk.sha256 != regular.sha256, "ImageJ no longer has the quirk; drop this deviation")
        let output = try run(regular)
        #expect(FilterInputs.sha256(output) == regular.sha256)
        #expect(FilterInputs.sha256(output) != quirk.sha256)
    }

    // MARK: Running a case

    func check(_ c: FilterGolden.Case) throws {
        let output = try run(c)
        let hash = FilterInputs.sha256(output)
        if hash == c.sha256 { return }
        let mismatches = c.samples.sorted { Int($0.key)! < Int($1.key)! }.compactMap { key, expected in
            let i = Int(key)!
            return FilterInputs.sampleMatches(expected, output, i)
                ? nil : "pixel \(i): ImageJ \(expected), Mancora \(FilterInputs.sample(output, i))"
        }
        Issue.record("output differs from ImageJ; \(mismatches.isEmpty ? "the samples match" : mismatches.joined(separator: "; "))")
    }

    /// A parameter the case must have (`#require` is ambiguous for `Bool?`).
    func value<T>(_ v: T?, sourceLocation: SourceLocation = #_sourceLocation) throws -> T {
        try #require(v, "parameter missing", sourceLocation: sourceLocation)
    }

    func run(_ c: FilterGolden.Case) throws -> Plane {
        let (input, width, _) = try #require(FilterInputs.plane(named: c.input))
        let p = c.params
        func binary(_ op: BinaryOperation) throws -> Plane {
            let options = BinaryOptions(
                blackBackground: try value(p.blackBackground), iterations: try value(p.iterations),
                count: try value(p.count), padEdges: try value(p.padEdges))
            return try input.binary(op, options: options, width: width)
        }
        switch c.filter {
        case "gaussian":
            return input.gaussianBlurred(
                sigmaX: try value(p.sigmaX), sigmaY: try value(p.sigmaY), accuracy: try value(p.accuracy),
                width: width)
        case "mean": return input.rankFiltered(.mean, radius: try value(p.radius), width: width)
        case "minimum": return input.rankFiltered(.minimum, radius: try value(p.radius), width: width)
        case "maximum": return input.rankFiltered(.maximum, radius: try value(p.radius), width: width)
        case "variance": return input.rankFiltered(.variance, radius: try value(p.radius), width: width)
        case "median": return input.rankFiltered(.median, radius: try value(p.radius), width: width)
        case "outliersBright":
            return input.rankFiltered(
                .removeOutliers(.bright, threshold: try value(p.threshold)), radius: try value(p.radius), width: width)
        case "outliersDark":
            return input.rankFiltered(
                .removeOutliers(.dark, threshold: try value(p.threshold)), radius: try value(p.radius), width: width)
        case "removeNaNs": return input.rankFiltered(.removeNaNs, radius: try value(p.radius), width: width)
        case "despeckle": return input.despeckled(width: width)
        case "smooth": return input.smoothed(width: width)
        case "sharpen": return input.sharpened(width: width)
        case "findEdges": return input.findingEdges(width: width)
        case "convolve":
            let values = try value(p.kernel).map { Float($0) }
            let kw = try value(p.kernelWidth)
            let kernel = try ConvolutionKernel(width: kw, height: values.count / kw, values: values)
            return input.convolved(with: kernel, normalize: try value(p.normalize), width: width)
        case "erode": return try binary(.erode)
        case "dilate": return try binary(.dilate)
        case "open": return try binary(.open)
        case "close": return try binary(.close)
        case "outline": return try binary(.outline)
        case "fill": return try binary(.fillHoles)
        case "skeletonize": return try binary(.skeletonize)
        default:
            Issue.record("unknown filter \(c.filter)")
            return input
        }
    }
}
